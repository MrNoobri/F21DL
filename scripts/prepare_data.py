"""Checks the raw data, builds data/processed/ and freezes the splits in data/splits/ (usage: prepare_data.py [fma|spec])."""
import re
import sys
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.config import (FMA_GENRES, PROCESSED, RAW_FMA, RAW_SPEC, SEED,  # noqa: E402
                        SPEC_GENRES, SPLITS)

REPORTS = ROOT / "results"


def _report(name, lines):
    REPORTS.mkdir(exist_ok=True)
    (REPORTS / f"data_check_{name}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


def _check(lines, ok, msg):
    lines.append(f"- {'OK  ' if ok else 'WARN'} {msg}")


def _counts_table(df):
    t = pd.crosstab(df["genre"], df["split"], margins=True, margins_name="total")
    return ["```", t[["training", "validation", "test", "total"]].to_string(), "```"]


def prepare_fma():
    tracks = pd.read_csv(RAW_FMA / "tracks.csv", index_col=0, header=[0, 1], low_memory=False)
    features = pd.read_csv(RAW_FMA / "features.csv", index_col=0, header=[0, 1, 2])
    # tracks.csv has a 2-row header, features.csv a 3-row header (descriptor, statistic, coefficient).
    small = tracks[tracks[("set", "subset")] == "small"]

    df = features.loc[small.index].copy()
    df.columns = ["_".join(c) for c in df.columns]  # e.g. mfcc_mean_01, chroma_cens_kurtosis_12
    feat_cols = list(df.columns)
    # Audio features only. IDs/artist/album metadata are deliberately excluded (leakage risk, Lecture 14).
    df["genre"] = small[("track", "genre_top")].astype(str)
    df["split"] = small[("set", "split")].astype(str)
    df.index.name = "track_id"

    X = df[feat_cols].to_numpy(dtype=float)
    lines = ["# FMA Small: data check", "", "Generated by `scripts/prepare_data.py`.", ""]
    _check(lines, len(df) == 8000, f"tracks: {len(df)} (expected 8000)")
    _check(lines, len(feat_cols) == 518, f"feature columns: {len(feat_cols)} (expected 518)")
    _check(lines, sorted(df["genre"].unique()) == sorted(FMA_GENRES),
           f"genres: {sorted(df['genre'].unique())}")
    _check(lines, set(df["split"]) == {"training", "validation", "test"}, f"splits: {sorted(set(df['split']))}")
    n_nan, n_inf = int(np.isnan(X).sum()), int(np.isinf(X).sum())
    _check(lines, n_nan == 0, f"missing values: {n_nan}")
    _check(lines, n_inf == 0, f"infinite values: {n_inf}")
    n_dup = int(df[feat_cols].duplicated().sum())
    _check(lines, n_dup == 0, f"duplicate feature rows: {n_dup}")
    # Group identical feature rows by a row hash; a group spanning splits would leak test tracks into training.
    row_hash = pd.util.hash_pandas_object(df[feat_cols], index=False)
    dups = df[row_hash.duplicated(keep=False)].groupby(row_hash)
    _check(lines, (dups["split"].nunique() == 1).all(), f"duplicate groups spanning splits: {int((dups['split'].nunique() > 1).sum())}")
    _check(lines, (dups["genre"].nunique() == 1).all(), f"duplicate groups with conflicting genres: {int((dups['genre'].nunique() > 1).sum())}")
    if n_dup:
        lines.append(f"- INFO duplicate track_ids: {[list(g.index) for _, g in dups]}")
    n_const = int((df[feat_cols].nunique() <= 1).sum())
    _check(lines, n_const == 0, f"constant feature columns: {n_const}")
    groups = Counter("_".join(c.split("_")[:-2]) for c in feat_cols)  # strip <stat>_<number>
    lines += ["", "Feature groups (columns per descriptor):", "",
              ", ".join(f"{g} {n}" for g, n in sorted(groups.items())), "",
              "Class counts per official split:", ""] + _counts_table(df)
    lines += ["", "Two example rows (first 6 feature columns):", "", "```",
              df[feat_cols[:6] + ["genre", "split"]].head(2).to_string(), "```"]

    PROCESSED.mkdir(parents=True, exist_ok=True)
    SPLITS.mkdir(parents=True, exist_ok=True)
    df.to_pickle(PROCESSED / "fma_small.pkl")
    df[["genre", "split"]].to_csv(SPLITS / "fma_splits.csv")
    _report("fma", lines)


def _key(s):
    # 'Hip-Hop', 'hiphop', 'HIP_HOP' -> 'hiphop', so label spellings in the Kaggle files still match.
    return re.sub(r"[^a-z]", "", str(s).lower())


def _find_spec_labels(npys):
    # Kaggle layout: spectrograms_unnormalized/data/<Genre>/clipNNNNN.npy (labelled) and test/ (unlabelled).
    genre_by_key = {_key(g): g for g in SPEC_GENRES}
    rows = [(p.stem, p, genre_by_key[_key(p.parent.name)]) for p in npys if _key(p.parent.name) in genre_by_key]
    if not rows:
        layout = sorted({str(p.parent.relative_to(RAW_SPEC)) for p in npys})[:10]
        sys.exit(f"No .npy files inside genre-named folders. Folders found: {layout}. Send this to Abdullah.")
    return pd.DataFrame(rows, columns=["id", "path", "genre"])


def prepare_spec():
    npys = sorted(RAW_SPEC.rglob("*.npy"))
    if not npys:
        sys.exit("No .npy files in data/raw/spec. Run: python scripts/download_data.py spec")
    index = _find_spec_labels(npys)
    index["path"] = index["path"].map(lambda p: p.relative_to(RAW_SPEC).as_posix())
    assert index["id"].is_unique, "duplicate spectrogram ids"

    # Stratified 70/15/15: split off 30%, then halve it, keeping genre proportions in every split.
    train, rest = train_test_split(index, test_size=0.30, stratify=index["genre"], random_state=SEED)
    val, test = train_test_split(rest, test_size=0.50, stratify=rest["genre"], random_state=SEED)
    index["split"] = "training"
    index.loc[val.index, "split"] = "validation"
    index.loc[test.index, "split"] = "test"

    # Shape, dtype and value checks on a fixed random sample of 300 files (loading all ~3.8 GB is slow).
    rng = np.random.default_rng(SEED)
    sample = rng.choice(len(index), size=min(300, len(index)), replace=False)
    arrays = [np.load(RAW_SPEC / index["path"].iloc[i]) for i in sample]
    shapes = Counter(a.shape for a in arrays)
    dtypes = Counter(str(a.dtype) for a in arrays)
    values = np.concatenate([a.ravel() for a in arrays])

    lines = ["# Mel-spectrograms: data check", "", "Generated by `scripts/prepare_data.py`.", ""]
    _check(lines, len(index) == 17382, f"labelled spectrograms: {len(index)} (expected 17382)")
    _check(lines, len(npys) - len(index) == 1446,
           f"unlabelled .npy files (Kaggle test set, unused): {len(npys) - len(index)} (expected 1446)")
    _check(lines, sorted(index["genre"].unique()) == sorted(SPEC_GENRES), f"genres: {sorted(index['genre'].unique())}")
    _check(lines, list(shapes) == [(128, 431)], f"shapes in a {len(arrays)}-file sample: {dict(shapes)}")
    lines.append(f"- INFO dtypes in sample: {dict(dtypes)}")
    _check(lines, not np.isnan(values).any(), f"NaN values in sample: {int(np.isnan(values).sum())}")
    lines.append(f"- INFO value range in sample: min {values.min():.3f}, max {values.max():.3f}, "
                 f"mean {values.mean():.3f}, std {values.std():.3f} (negative values suggest a dB scale)")
    lines.append(f"- INFO example ids: {', '.join(index['id'].head(5))} "
                 "(look for track/clip patterns that reveal clips from the same song)")
    lines += ["", "Class counts per split (stratified 70/15/15, seed 42):", ""]
    lines += _counts_table(index)

    PROCESSED.mkdir(parents=True, exist_ok=True)
    SPLITS.mkdir(parents=True, exist_ok=True)
    index[["id", "path", "genre"]].to_csv(PROCESSED / "spec_index.csv", index=False)
    # Only id -> split is committed; labels stay in the gitignored index (Kaggle forbids redistribution).
    index[["id", "split"]].sort_values("id").to_csv(SPLITS / "spec_splits.csv", index=False)
    _report("spec", lines)


if __name__ == "__main__":
    which = sys.argv[1] if len(sys.argv) > 1 else "all"
    if which in ("fma", "all"):
        prepare_fma()
    if which in ("spec", "all"):
        prepare_spec()
